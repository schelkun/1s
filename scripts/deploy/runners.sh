#!/usr/bin/env bash
# Gitea Actions runner pool management.
#
#   runners.sh reconcile   create/update runners 1..GITEA_RUNNER_COUNT (one at a
#                          time, letting running jobs finish) and deregister and
#                          remove runners above that count
#   runners.sh status      show runners
#   runners.sh prune       prune old images/containers inside every runner's
#                          PRIVATE Docker daemon (never the host daemon)
#
# Each runner is an independent compose project with its own rootless Docker
# daemon, network (<GITEA_RUNNER_SUBNET_POOL>.N.0/24), volumes and limits.
set -euo pipefail

# shellcheck source=scripts/lib/deploy.sh
source "$(dirname "${BASH_SOURCE[0]}")/../lib/deploy.sh"

RT_BASE="${RUNTIME_DIR}/gitea-runners"
GITEA_C="${ONES_PREFIX}-gitea"
RUNNER_UID=1000

runner_c() { printf '%s-gitea-runner-%s\n' "${ONES_PREFIX}" "$1"; }

runner_compose() {
  local i="$1"; shift
  local overlay="${ONES_ROOT}/compose/gitea-runners/compose.${GITEA_RUNNER_ISOLATION}.yml"
  compose_cmd "${ONES_ROOT}/compose/gitea-runners" "${RT_BASE}/${i}/compose.env" "${overlay}" -- "$@"
}

existing_indices() {
  docker ps -a --format '{{.Names}}' | sed -n "s/^${ONES_PREFIX}-gitea-runner-\([0-9]\{1,3\}\)$/\1/p" | sort -n
  if [[ -d "${RT_BASE}" ]]; then find "${RT_BASE}" -mindepth 1 -maxdepth 1 -type d -printf '%f\n' | grep -E '^[0-9]+$' || true; fi
}

apparmor_profile() {
  local p="${GITEA_RUNNER_APPARMOR_PROFILE}"
  [[ "${GITEA_RUNNER_ISOLATION}" == rootless ]] || { echo unconfined; return; }
  [[ "${p}" == unconfined ]] && { echo unconfined; return; }
  if [[ ! -d /sys/kernel/security/apparmor ]]; then
    warn "AppArmor is not active on this host; using apparmor=unconfined for runners." ; echo unconfined; return
  fi
  if grep -q "^${p} " /sys/kernel/security/apparmor/profiles 2>/dev/null; then echo "${p}"; return; fi
  if [[ "$(cat /proc/sys/kernel/apparmor_restrict_unprivileged_userns 2>/dev/null || echo 0)" == 1 ]]; then
    die "AppArmor profile ${p} is not loaded, but this kernel restricts user namespaces. Re-run scripts/server/bootstrap.sh."
  fi
  warn "AppArmor profile ${p} not loaded; user namespaces are unrestricted here, using unconfined."
  echo unconfined
}

job_docker_host() { if is_true "${GITEA_RUNNER_JOB_DOCKER}"; then echo '""'; else echo '"-"'; fi; }

render_runner() {
  local i="$1" dir="${RT_BASE}/$1" profile="$2"
  install -d -m 0750 "${dir}"
  chgrp "${RUNNER_UID}" "${dir}" 2>/dev/null || true
  # Consumed by write_env through indirection.
  # shellcheck disable=SC2034
  { RUNNER_INDEX="${i}"; RUNNER_NAME="${ONES_PREFIX}-runner-${i}-$(hostname -s)"
    RUNNER_SUBNET="$(pool_subnet "${GITEA_RUNNER_SUBNET_POOL}" "${i}")"; RUNNER_RUNTIME_DIR="${dir}"; }
  GITEA_RUNNER_APPARMOR_PROFILE="${profile}"
  write_env "${dir}/compose.env" 0600 ONES_PREFIX RUNNER_INDEX RUNNER_NAME RUNNER_SUBNET RUNNER_RUNTIME_DIR \
    GITEA_DOMAIN GITEA_RUNNER_IMAGE GITEA_RUNNER_LABELS GITEA_RUNNER_CPUS GITEA_RUNNER_MEMORY \
    GITEA_RUNNER_PIDS_LIMIT GITEA_RUNNER_SHUTDOWN_TIMEOUT GITEA_RUNNER_APPARMOR_PROFILE
  cat <<EOF | atomic_write "${dir}/config.yaml" 0644
# Generated by 1s (scripts/deploy/runners.sh). Do not edit on the server.
log:
  level: info
runner:
  file: /data/.runner
  capacity: ${GITEA_RUNNER_CAPACITY}
  timeout: ${GITEA_RUNNER_JOB_TIMEOUT}
  shutdown_timeout: ${GITEA_RUNNER_SHUTDOWN_TIMEOUT}
  insecure: false
$(if [[ -n "${GITEA_RUNNER_CA_FILE:-}" ]]; then echo "  ca_file: /etc/1s-runner/ca.crt"; fi)
  fetch_timeout: 5s
  fetch_interval: 2s
cache:
  enabled: true
  dir: /data/cache
container:
  network: ""
  privileged: false
  options: ""
  valid_volumes: []
  docker_host: $(job_docker_host)
  force_pull: false
host:
  workdir_parent: /data/host-work
EOF
  [[ -f "${dir}/registration-token" ]] || install -m 0400 -o "${RUNNER_UID}" /dev/null "${dir}/registration-token"
  if [[ -n "${GITEA_RUNNER_CA_FILE:-}" ]]; then
    [[ -r "${GITEA_RUNNER_CA_FILE}" ]] || die "GITEA_RUNNER_CA_FILE not readable: ${GITEA_RUNNER_CA_FILE}"
    install -m 0644 "${GITEA_RUNNER_CA_FILE}" "${dir}/ca.crt"
  else
    : >"${dir}/ca.crt"; chmod 0644 "${dir}/ca.crt"
  fi
}

runner_registered() {
  local i="$1"
  docker run --rm -v "${ONES_PREFIX}-gitea-runner-${i}-data:/data:ro" "${HELPER_IMAGE}" test -s /data/.runner 2>/dev/null
}

set_token() { # set_token DIR TOKEN|'' -- write the one-time registration token
  local f="$1/registration-token"
  printf '%s' "$2" >"${f}.tmp"; chown "${RUNNER_UID}" "${f}.tmp"; chmod 0400 "${f}.tmp"
  cat "${f}.tmp" >"${f}"; rm -f "${f}.tmp"  # keep the inode: it is bind-mounted
}

reconcile_one() {
  local i="$1" profile="$2" dir="${RT_BASE}/$1" token=""
  render_runner "${i}" "${profile}"
  docker volume create "${ONES_PREFIX}-gitea-runner-${i}-data" >/dev/null
  if ! runner_registered "${i}"; then
    log "Runner ${i}: requesting registration token"
    token="$(docker exec -u git "${GITEA_C}" gitea actions generate-runner-token 2>/dev/null | tail -n1 | tr -d '[:space:]')"
    [[ -n "${token}" ]] || die "Could not generate a runner registration token."
    set_token "${dir}" "${token}"
  fi
  runner_compose "${i}" up -d --remove-orphans
  if [[ -n "${token}" ]]; then
    local waited=0
    until docker exec "$(runner_c "${i}")" test -s /data/.runner 2>/dev/null; do
      (( waited >= 180 )) && { set_token "${dir}" ""; docker logs --tail 30 "$(runner_c "${i}")" >&2; die "Runner ${i} did not register within 180s."; }
      sleep 3; waited=$((waited + 3))
    done
    set_token "${dir}" ""   # the token is reusable; never leave it on disk
    log "Runner ${i}: registered."
  fi
  local waited=0
  until docker exec "$(runner_c "${i}")" docker info >/dev/null 2>&1; do
    (( waited >= 120 )) && { docker logs --tail 30 "$(runner_c "${i}")" >&2; die "Runner ${i}: private Docker daemon did not start."; }
    sleep 3; waited=$((waited + 3))
  done
  log "Runner ${i}: running ($(runner_c "${i}"))."
}

gitea_api() { # gitea_api METHOD PATH -- authenticated as the bootstrap admin
  curl -fsS -X "$1" -u "${GITEA_ADMIN_USER}:${GITEA_ADMIN_PASSWORD}" \
    -H 'Accept: application/json' "http://127.0.0.1:${GITEA_LOCAL_PORT}/api/v1$2"
}

deregister_one() {
  local i="$1" id
  id="$(docker run --rm -v "${ONES_PREFIX}-gitea-runner-${i}-data:/data:ro" "${HELPER_IMAGE}" cat /data/.runner 2>/dev/null \
        | sed -n 's/.*"id"[[:space:]]*:[[:space:]]*\([0-9][0-9]*\).*/\1/p' | head -n1 || true)"
  if [[ -n "${id}" ]]; then
    if gitea_api DELETE "/admin/actions/runners/${id}" >/dev/null 2>&1; then
      log "Runner ${i}: deregistered from Gitea (id ${id})."
    else
      warn "Runner ${i}: could not deregister id ${id} via API; remove it in Site Administration > Actions > Runners."
    fi
  fi
}

remove_one() {
  local i="$1"
  log "Runner ${i}: stopping (waits up to ${GITEA_RUNNER_SHUTDOWN_TIMEOUT} for running jobs)"
  if [[ -f "${RT_BASE}/${i}/compose.env" ]]; then
    runner_compose "${i}" stop || true
  else
    docker stop -t 1800 "$(runner_c "${i}")" >/dev/null 2>&1 || true
  fi
  deregister_one "${i}"
  if [[ -f "${RT_BASE}/${i}/compose.env" ]]; then
    runner_compose "${i}" down --volumes --remove-orphans || true
  else
    docker rm -f "$(runner_c "${i}")" >/dev/null 2>&1 || true
    docker volume rm "${ONES_PREFIX}-gitea-runner-${i}-data" "${ONES_PREFIX}-gitea-runner-${i}-docker" >/dev/null 2>&1 || true
    docker network rm "${ONES_PREFIX}-gitea-runner-${i}" >/dev/null 2>&1 || true
  fi
  rm -rf -- "${RT_BASE:?}/${i}"
  log "Runner ${i}: removed."
}

cmd_reconcile() {
  local want="${GITEA_RUNNER_COUNT}" i profile
  profile="$(apparmor_profile)"
  ensure_image "${GITEA_RUNNER_IMAGE}"
  ensure_image "${HELPER_IMAGE}"
  for ((i = 1; i <= want; i++)); do reconcile_one "${i}" "${profile}"; done
  for i in $(existing_indices | sort -nu); do
    (( i > want )) && remove_one "${i}"
  done
  log "Runner pool: ${want} runner(s) x capacity ${GITEA_RUNNER_CAPACITY}."
}

cmd_status() {
  local i c
  for i in $(existing_indices | sort -nu); do
    c="$(runner_c "${i}")"
    printf '%-28s %-10s registered=%s\n' "${c}" "$(container_health "${c}")" \
      "$(docker exec "${c}" test -s /data/.runner 2>/dev/null && echo yes || echo no)"
  done
}

cmd_prune() {
  local i c
  for i in $(existing_indices | sort -nu); do
    c="$(runner_c "${i}")"
    [[ "$(container_health "${c}")" == running ]] || continue
    log "Pruning private Docker daemon of ${c}"
    docker exec "${c}" docker system prune -af --filter "until=${GITEA_RUNNER_PRUNE_AFTER}" >/dev/null || warn "Prune failed for ${c}"
  done
}

main() {
  require_root
  config_load_server
  config_validate shared gitea
  case "${1:-}" in
    reconcile) with_lock runners cmd_reconcile ;;
    status)    cmd_status ;;
    prune)     with_lock runners cmd_prune ;;
    *) sed -n '2,13p' "$0" | sed 's/^# \{0,1\}//'; exit 2 ;;
  esac
}

main "$@"
